"""Scrape the classic APA Division 12 (Society of Clinical Psychology)
research-supported psychological treatments list via the Wayback Machine.

The live site (div12.org -> societyofclinicalpsychology.org) sits behind a
Cloudflare challenge and has retired the classic ~90-treatment list in favor
of a new Tolin-criteria review process (5 treatments published so far). The
classic list remains the standard reference for adult ESTs, so we pull each
archived treatment page and record the snapshot date as provenance.

URL list comes from a Wayback CDX query, cached in
scrapers/cache/div12-old-urls.txt (regenerated by refresh.py).
"""
import json
import os
import re
import urllib.parse

from common import ROOT, clean, fetch, fetch_json, save_source, strip_tags

URL_LIST = os.path.join(ROOT, "scrapers", "cache", "div12-old-urls.txt")
CDX = (
    "http://web.archive.org/cdx/search/cdx?url=div12.org/psychological-treatments/treatments/*"
    "&output=json&collapse=urlkey&filter=statuscode:200"
)

SKIP_SLUGS = {"treatments", "2147483647"}


def get_urls():
    if os.path.exists(URL_LIST):
        with open(URL_LIST) as f:
            urls = [l.strip() for l in f if l.strip()]
    else:
        rows = fetch_json(CDX) or []
        urls = sorted(
            {r[2].replace(":80", "") for r in rows[1:] if re.search(r"treatments/[a-z0-9_-]+/?$", r[2], re.I)}
        )
        with open(URL_LIST, "w") as f:
            f.write("\n".join(urls))
    out = []
    for u in urls:
        slug = u.rstrip("/").split("/")[-1]
        if slug not in SKIP_SLUGS:
            out.append(u)
    return out


def main():
    urls = get_urls()
    print(f"Div12: {len(urls)} archived treatment pages")
    records = []
    for url in urls:
        avail = fetch_json(
            "http://archive.org/wayback/available?url=" + urllib.parse.quote(url, safe="")
        )
        snap = (avail or {}).get("archived_snapshots", {}).get("closest", {})
        if not snap.get("available"):
            continue
        html = fetch(snap["url"])
        if not html:
            continue

        title_m = re.search(r"<title>(.*?)</title>", html, re.S)
        title = strip_tags(title_m.group(1)) if title_m else ""
        title = re.split(r"\s*[|«»]\s*", title)[0].strip()
        if not title:
            continue

        # Rating text, e.g. "Strong Research Support" / "Modest Research Support"
        rating = ""
        rm = re.search(
            r"(Strong|Modest|Controversial|Insufficient Evidence|No)[\s/]*(?:to\s+\w+\s+)?Research Support",
            strip_tags(html),
        )
        if rm:
            rating = clean(rm.group(0))

        # "Treatment for Condition" -> split name/condition
        name, condition = title, ""
        tm = re.split(r"\s+for\s+", title, maxsplit=1)
        if len(tm) == 2:
            name, condition = tm[0].strip(), tm[1].strip()

        desc = ""
        dm = re.search(
            r"(?:Essence of the therapy|Basic premise)\s*:?\s*</[^>]+>\s*(?:<[^>]+>)*([^<]{40,})",
            html,
        )
        if dm:
            desc = clean(dm.group(1))[:500]

        records.append(
            {
                "name": clean(name),
                "fullTitle": clean(title),
                "problem": clean(condition),
                "rating": rating,
                "summary": desc,
                "url": url,
                "archivedUrl": snap["url"],
                "archivedAt": snap.get("timestamp", "")[:8],
            }
        )

    save_source(
        "div12",
        "APA Division 12 (Society of Clinical Psychology) – Research-Supported Psychological Treatments",
        "https://societyofclinicalpsychology.org/resource/psychological-treatments/",
        records,
        notes=(
            "Classic Division 12 empirically supported treatments list (primarily adult "
            "populations), retrieved from Internet Archive snapshots of div12.org. The "
            "society is migrating to a new Tolin-criteria review system; ratings here "
            "reflect the classic Chambless criteria (Strong = 2+ rigorous RCTs by "
            "independent teams; Modest = at least one good trial). Each record carries "
            "its snapshot date."
        ),
        rating_scale={
            "Strong Research Support": "2+ well-designed RCTs by independent investigators",
            "Modest Research Support": "At least one good RCT or several smaller studies",
            "Controversial Research Support": "Mixed or disputed findings",
        },
    )
    # Persist url list for refresh diffing
    print(json.dumps({"urls": len(urls), "parsed": len(records)}))


if __name__ == "__main__":
    main()
